/**
 * Every pattern of every locale's outbound-screen bank has to match at least
 * one realistic sentence below.
 *
 * A pattern that can never fire is a contract the screen only appears to
 * enforce, and nothing else notices: the bank stays green because the other
 * patterns carry the tests. JavaScript's `\b` is an ASCII boundary, so next to
 * an accented letter it never matches: French "à cause de", "causé" and
 * "continuez à", the French and Italian "probabilité" / "probabilità" and the
 * Dutch "één procent" all walked past their patterns, and a `\w*` stem cannot
 * run through "ł", so Polish "doprowadziło do" did too. A new pattern needs a
 * sentence here; a sentence that stops matching after an edit points at the
 * pattern it broke.
 */
