function patternsOf(bank: LocaleBank): Array<[string, RegExp]> {
  const groups: Record<string, readonly RegExp[]> = {
    doseChangeClass: bank.doseChangeClass(bank.vocabulary(null)),
    dose: bank.dose,
    risk: bank.risk,
    causal: bank.causal,
    continuation: [bank.continuation],
    changeStem: [bank.changeStem],
  };
  return Object.entries(groups).flatMap(([group, patterns]) =>
    patterns.map((pattern, index): [string, RegExp] => [
      `${group}[${index}]`,
      pattern,
    ]),
  );
}

describe("outbound-screen banks: no pattern is dead", () => {
  it("walks a real number of patterns", () => {
    const total = locales.reduce(
      (sum, locale) => sum + patternsOf(BANKS[locale]).length,
      0,
    );
    expect(total).toBeGreaterThan(300);
  });

  it.each(locales)(
    "every %s pattern matches one of its sentences",
    (locale) => {
      const dead = patternsOf(BANKS[locale])
        .filter(
          ([, pattern]) => !SENTENCES[locale].some((s) => pattern.test(s)),
        )
        .map(([name, pattern]) => `${name} /${pattern.source.slice(0, 120)}/`);
      expect(dead, `${locale} patterns no sentence matches`).toEqual([]);
    },
  );

  it.each(locales)(
    "no %s pattern puts an ASCII word boundary next to an accented letter",
    (locale) => {
      const offenders = patternsOf(BANKS[locale])
        .filter(([, pattern]) => accentedBoundaries(pattern.source).length > 0)
        .map(([name]) => name);
      expect(offenders, `${locale} outbound-screen patterns`).toEqual([]);
    },
  );
});
